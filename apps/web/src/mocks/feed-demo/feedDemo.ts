const HORA = 3_600_000

function idAutor(nombre: string) {
  return `demo-${nombre
    .toLowerCase()
    .normalize('NFD')
    .replace(/[^a-z]+/g, '-')}`
}

/** Publicaciones de corredores de Loja con fotos, ruta, metricas y comentarios. */
export function publicacionesDemo(ahora = Date.now()): PublicacionRemota[] {
  return DEMO.map((d) => {
    const t0 = ahora - d.horas * HORA
    const ruta = d.ruta ? RUTAS[d.ruta] : []
    const ultimo = d.com[d.com.length - 1]
    return {
      id: d.id,
      autorId: idAutor(d.autor),
      autor: d.autor,
      titulo: d.titulo,
      inicioMs: t0,
      distanciaKm: d.km,
      segundos: d.seg,
      desnivelM: d.des,
      imagenes: d.fotos.map((n) => FOTOS[n - 1]),
      compartidos: d.reposts,
      autorKm: d.autorKm,
      ultimoComentario: ultimo ? { autor: ultimo[0], texto: ultimo[1] } : null,
      likes: d.likes,
      comentarios: d.com.length,
      puntos: ruta.map(([lat, lng], k) => ({
        lat,
        lng,
        tiempoMs: t0 + Math.round((k * d.seg * 1000) / Math.max(1, ruta.length - 1)),
        precisionM: 5,
        altitudM: null,
      })),
      propia: false,
    }
  })
}

/** Hilo completo de comentarios de una publicacion de ejemplo. */
export function comentariosDemo(id: string, ahora = Date.now()): ComentarioPublicacion[] | null {
  const d = DEMO.find((x) => x.id === id)
  if (!d) return null
  const t0 = ahora - d.horas * HORA
  return d.com.map(([autor, texto], k) => ({
    id: `${id}-c${k}`,
    autorId: idAutor(autor),
    autor,
    texto,
    creadoMs: t0 + (k + 1) * 20 * 60_000,
  }))
}
